"""
Master Script for Creating All RAG System Visualizations
Runs all visualization scripts and provides a comprehensive summary
"""

import os
import sys
import subprocess
from datetime import datetime

def run_script(script_name, description):
    """Run a visualization script and handle errors"""
    print(f"\n{'='*60}")
    print(f"Running: {description}")
    print(f"Script: {script_name}")
    print(f"{'='*60}")
    
    try:
        result = subprocess.run([sys.executable, script_name], 
                              capture_output=True, text=True, check=True)
        print(result.stdout)
        if result.stderr:
            print("Warnings:", result.stderr)
        return True
    except subprocess.CalledProcessError as e:
        print(f"Error running {script_name}:")
        print(f"Return code: {e.returncode}")
        print(f"Error output: {e.stderr}")
        return False
    except Exception as e:
        print(f"Unexpected error running {script_name}: {str(e)}")
        return False

def check_output_files(output_dir):
    """Check which visualization files were created"""
    expected_files = [
        'rag_system_architecture.png',
        'experiment_design_overview.png',
        'dataset_performance_comparison.png',
        'summary_dashboard.png',
        'ablation_study_comparison.png',
        'component_contribution.png',
        'performance_heatmap.png',
        'comprehensive_radar_chart.png',
        'retrieval_analysis_dashboard.png',
        'system_comparison_matrix.png'
    ]
    
    created_files = []
    missing_files = []
    
    for filename in expected_files:
        filepath = os.path.join(output_dir, filename)
        if os.path.exists(filepath):
            file_size = os.path.getsize(filepath)
            created_files.append((filename, file_size))
        else:
            missing_files.append(filename)
    
    return created_files, missing_files

def generate_summary_report(output_dir, created_files, missing_files, execution_time):
    """Generate a summary report of the visualization creation process"""
    
    report_content = f"""
# RAG System Visualization Generation Report

**Generated on:** {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}
**Total Execution Time:** {execution_time:.2f} seconds
**Output Directory:** {output_dir}

## Successfully Created Visualizations

"""
    
    for filename, file_size in created_files:
        size_kb = file_size / 1024
        report_content += f"- ✅ **{filename}** ({size_kb:.1f} KB)\n"
    
    if missing_files:
        report_content += f"\n## Missing Visualizations\n\n"
        for filename in missing_files:
            report_content += f"- ❌ **{filename}**\n"
    
    report_content += f"""

## Visualization Categories

### 1. System Architecture & Design
- `rag_system_architecture.png` - Complete RAG system architecture diagram
- `experiment_design_overview.png` - Ablation study design overview

### 2. Performance Analysis
- `dataset_performance_comparison.png` - Performance across different datasets
- `ablation_study_comparison.png` - Component contribution analysis
- `component_contribution.png` - Individual component impact analysis

### 3. Comprehensive Dashboards
- `summary_dashboard.png` - Overall system performance dashboard
- `performance_heatmap.png` - Performance matrix across experiments and datasets
- `comprehensive_radar_chart.png` - Multi-dimensional performance comparison

### 4. Advanced Analysis
- `retrieval_analysis_dashboard.png` - Detailed retrieval system analysis
- `system_comparison_matrix.png` - System variants comparison table

## Usage Instructions

1. **For Academic Papers:** Use high-resolution PNG files (300 DPI) directly
2. **For Presentations:** All charts are optimized for projection and printing
3. **For Web Display:** Files are web-ready with appropriate compression

## Technical Details

- **Resolution:** 300 DPI for publication quality
- **Format:** PNG with transparent backgrounds where appropriate
- **Color Scheme:** Colorblind-friendly palettes used throughout
- **Font Sizes:** Optimized for readability when scaled

## Data Sources

- Primary data from: `/home/pushihao/RAG/Reports/experiments/advanced_evaluation_results/`
- Simulated ablation data based on typical RAG system performance patterns
- All metrics are clearly labeled as actual or simulated in the visualizations

## Next Steps

1. Review all generated visualizations for accuracy and clarity
2. Integrate selected charts into research papers or presentations
3. Update visualizations when new experimental data becomes available
4. Consider generating additional specialized charts based on specific research needs

---
*Generated by RAG System Visualization Pipeline*
"""
    
    # Save the report
    report_path = os.path.join(output_dir, 'visualization_generation_report.md')
    with open(report_path, 'w', encoding='utf-8') as f:
        f.write(report_content)
    
    return report_path

def main():
    """Main function to run all visualization scripts"""
    
    start_time = datetime.now()
    
    print("RAG System Visualization Generation Pipeline")
    print("=" * 60)
    print(f"Started at: {start_time.strftime('%Y-%m-%d %H:%M:%S')}")
    
    # Define scripts to run
    scripts = [
        ('create_architecture_diagram.py', 'System Architecture Diagrams'),
        ('create_performance_charts.py', 'Performance Comparison Charts'),
        ('create_advanced_charts.py', 'Advanced Visualization Charts')
    ]
    
    # Track success/failure
    successful_scripts = []
    failed_scripts = []
    
    # Run each script
    for script_name, description in scripts:
        if run_script(script_name, description):
            successful_scripts.append((script_name, description))
        else:
            failed_scripts.append((script_name, description))
    
    # Check output files
    output_dir = "/home/pushihao/RAG/Reports/docs/pics"
    created_files, missing_files = check_output_files(output_dir)
    
    # Calculate execution time
    end_time = datetime.now()
    execution_time = (end_time - start_time).total_seconds()
    
    # Generate summary report
    report_path = generate_summary_report(output_dir, created_files, missing_files, execution_time)
    
    # Print final summary
    print(f"\n{'='*60}")
    print("VISUALIZATION GENERATION COMPLETE")
    print(f"{'='*60}")
    print(f"Execution Time: {execution_time:.2f} seconds")
    print(f"Successful Scripts: {len(successful_scripts)}/{len(scripts)}")
    print(f"Created Files: {len(created_files)}")
    print(f"Missing Files: {len(missing_files)}")
    print(f"Output Directory: {output_dir}")
    print(f"Summary Report: {report_path}")
    
    if successful_scripts:
        print(f"\n✅ Successfully executed:")
        for script, desc in successful_scripts:
            print(f"   - {desc}")
    
    if failed_scripts:
        print(f"\n❌ Failed to execute:")
        for script, desc in failed_scripts:
            print(f"   - {desc}")
    
    if created_files:
        print(f"\n📊 Generated visualizations:")
        for filename, size in created_files:
            print(f"   - {filename} ({size/1024:.1f} KB)")
    
    if missing_files:
        print(f"\n⚠️  Missing visualizations:")
        for filename in missing_files:
            print(f"   - {filename}")
    
    print(f"\n🎉 Visualization pipeline completed!")
    print(f"All files are ready for use in research papers and presentations.")
    
    return len(failed_scripts) == 0  # Return True if all scripts succeeded

if __name__ == "__main__":
    success = main()
    sys.exit(0 if success else 1)